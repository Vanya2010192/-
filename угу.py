слова = ["яблоко", "банан", "груша", "апельсин", "киви"]
загаданное_слово = слова[0]  # Для простоты, будем использовать первое слово из списка
угаданные_буквы = []
попытки = 7

print("Добро пожаловать в игру 'Поле чудес'!")
print("Угадайте слово, состоящее из " + str(len(загаданное_слово)) + " букв.")

while попытки > 0:
    текущее_слово = ''
    for буква in загаданное_слово:
        if буква in угаданные_буквы:
            текущее_слово += буква
        else:
            текущее_слово += '_'
    
    print("Слово: ", текущее_слово)

    буква = input("Введите букву: ").lower()

    # Проверка на допустимые символы (только русские буквы)
    if len(буква) != 1 or not ('а' <= буква <= 'я' or буква == 'ё'):
        print("Пожалуйста, введите одну русскую букву.")
        continue

    if буква in угаданные_буквы:
        print("Вы уже называли эту букву. Попробуйте другую.")
        continue

    угаданные_буквы.append(буква)

    if буква in загаданное_слово:
        print("Поздравляем! Буква '" + буква + "' есть в слове.")
    else:
        попытки -= 1
        print("К сожалению, буквы '" + буква + "' нет в слове. Осталось попыток: " + str(попытки))

    if all(буква in угаданные_буквы for буква in загаданное_слово):
        print("Поздравляем! Вы угадали слово: '" + загаданное_слово + "'")
        break
else:
    print("Вы проиграли! Загаданное слово было: '" + загаданное_слово + "'")
    
